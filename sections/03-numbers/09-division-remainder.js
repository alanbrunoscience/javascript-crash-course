'use strict';

/**
 * Operations
 *
 * → As you might expect, numbers can be multiplied and divided. We've already done an example of multiplication
 * at the beginning of the course, using the '*' operator.
 *
 * → For division, you need to use the '/' operator.
 *
 * --------------------------------------------------------------------------------------------------------------
 *
 * Division Remainder
 *
 * → You can also use the remainder operator '%' which returns the division remainder. Here's an example:
 *
 */

console.log(8 % 2); // Division remainder is 0 (8 = 4 * 2 + 0)
console.log(7 % 2); // Division remainder is 1 (7 = 3 * 2 + 1)